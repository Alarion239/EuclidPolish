"""Angular (flat-sky 2D Fourier) power-spectrum comparison of HR vs SR.

For each band we measure, in the Fourier domain and averaged azimuthally:

- the **transfer function** ``T(k) = sqrt(P_SR(k) / P_HR(k))`` — whether SR
  carries the right amount of power at scale ``k`` (over-smoothing → T<1,
  hallucinated/excess power → T>1), and
- the **cross-correlation coefficient** ``r(k) = P_HR×SR(k) /
  sqrt(P_HR(k)·P_SR(k))`` — whether the power at ``k`` is the *real* structure
  (r→1) or decorrelated/invented (r→0).

``r(k)`` is the direct answer to "how well does the model resolve features",
especially in the super-resolution regime above the LR sampling limit
(5 cyc/arcsec on the 0.10" LR grid) up to the HR-grid Nyquist (10 cyc/arcsec on
the 0.05" SR/HR grid).

We run this on the **sky validation set** synced through the /sky tab — large
fields (≈510×510 at 0.05"), which carry far more Fourier modes per k-bin (so
T(k)/r(k) are smooth) and real structure across scales, unlike the mode-starved
106² evaluation cutouts. HR is the ``clean`` record (the deconvolved-sky target
the model is trained to output); SR is the per-field cube generated by the /sky
"Generate SR" button (``data/vis/sky_sr/sr_<subset>_<idx>.npy``), paired by
record index.

Estimator: per-**field** median ± 16–84% inter-field spread (each field weighted
equally). This is deliberate — a single bright star carries ~flux², so a few
star-dominated fields (which the model rejects by design) would otherwise
dominate a raw stacked sum; the median is robust to them, and the asinh space
further compresses their dynamic range.

The math (window, binning, ratios) is pure numpy/scipy; the renderer lazily
imports matplotlib and the TFRecord/sky loaders.
"""

from __future__ import annotations

import os

import numpy as np

from euclid_polish.config import Config

#: per-band line colours (blue→red, roughly by pivot wavelength)
BAND_COLORS: dict[str, str] = {
    "VIS": "#3b6fb0", "Y_E": "#5aae61", "J_E": "#e08214", "H_E": "#d6604d",
}

#: LR sampling Nyquist on the 0.10" grid — the super-resolution boundary.
LR_NYQUIST_CYC_ARCSEC = 1.0 / (2.0 * Config.VIS_PIXEL_SCALE_ARCSEC)  # 5.0


# --------------------------------------------------------------------------- #
# Core math (unit-tested)                                                      #
# --------------------------------------------------------------------------- #
def tukey_window_2d(n: int, alpha: float = 0.25) -> np.ndarray:
    """Separable 2D Tukey window (``n×n``) to suppress finite-stamp leakage."""
    from scipy.signal.windows import tukey

    w = tukey(n, alpha)
    return np.outer(w, w)


def cross_power_2d(
    a: np.ndarray, b: np.ndarray, window: np.ndarray | None = None
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """2D auto/cross power for two same-shape real images.

    Each image is mean-subtracted (kills the DC term) and multiplied by
    ``window`` before the FFT. Returns ``(P_aa, P_bb, P_ab)`` as unshifted 2D
    real arrays, where ``P_ab = Re(A · conj(B))``.
    """
    a = np.asarray(a, dtype=np.float64)
    b = np.asarray(b, dtype=np.float64)
    if a.shape != b.shape:
        raise ValueError(f"shape mismatch: {a.shape} vs {b.shape}")
    if window is not None:
        a = (a - a.mean()) * window
        b = (b - b.mean()) * window
    else:
        a = a - a.mean()
        b = b - b.mean()
    fa = np.fft.fft2(a)
    fb = np.fft.fft2(b)
    p_aa = (fa * np.conj(fa)).real
    p_bb = (fb * np.conj(fb)).real
    p_ab = (fa * np.conj(fb)).real
    return p_aa, p_bb, p_ab


def k_magnitude_2d(n: int, pixel_scale_arcsec: float) -> np.ndarray:
    """``|k|`` (cycles/arcsec) for an ``n×n`` unshifted FFT grid."""
    f = np.fft.fftfreq(n, d=pixel_scale_arcsec)  # cycles / arcsec
    kx, ky = np.meshgrid(f, f, indexing="xy")
    return np.hypot(kx, ky)


def log_k_edges(
    pixel_scale_arcsec: float, kmin: float = 0.2, nbins: int = 24
) -> np.ndarray:
    """Log-spaced k-bin edges from ``kmin`` to the Nyquist ``1/(2·pixscale)``."""
    k_nyq = 1.0 / (2.0 * pixel_scale_arcsec)
    return np.geomspace(kmin, k_nyq, nbins + 1)


def bin_powers(
    hr: np.ndarray,
    sr: np.ndarray,
    pixel_scale_arcsec: float,
    k_edges: np.ndarray,
    window: np.ndarray | None = None,
) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """Azimuthally-binned ``(p_hr, p_sr, p_cross, count)`` for one HR/SR pair."""
    n = hr.shape[0]
    if window is None:
        window = tukey_window_2d(n)
    p_hr2, p_sr2, p_x2 = cross_power_2d(hr, sr, window)
    kmag = k_magnitude_2d(n, pixel_scale_arcsec).ravel()
    nb = len(k_edges) - 1
    idx = np.digitize(kmag, np.asarray(k_edges, float)) - 1
    keep = (idx >= 0) & (idx < nb)
    idx = idx[keep]
    bh = np.bincount(idx, weights=p_hr2.ravel()[keep], minlength=nb)
    bs = np.bincount(idx, weights=p_sr2.ravel()[keep], minlength=nb)
    bx = np.bincount(idx, weights=p_x2.ravel()[keep], minlength=nb)
    bc = np.bincount(idx, minlength=nb).astype(float)
    return bh, bs, bx, bc


def ratios_from_powers(
    bh: np.ndarray, bs: np.ndarray, bx: np.ndarray, bc: np.ndarray
) -> tuple[np.ndarray, np.ndarray]:
    """``(T, r)`` from binned powers; empty bins → NaN. r ∈ [-1, 1] per object."""
    with np.errstate(divide="ignore", invalid="ignore"):
        t = np.sqrt(bs / bh)
        r = bx / np.sqrt(bh * bs)
    empty = bc <= 0
    t[empty] = np.nan
    r[empty] = np.nan
    return t, r


# --------------------------------------------------------------------------- #
# Ensemble power spectrum: HR vs ensemble-mean + the disagreement spectrum     #
# --------------------------------------------------------------------------- #
class EnsembleSpectrumAccumulator:
    """Stacked HR / ensemble-mean / disagreement power on a fixed k-grid.

    Fed one field at a time (single band, HR-grid resolution). Accumulates, per
    azimuthal k-bin: HR auto-power, ensemble-mean SR auto-power, the HR×mean
    cross-power, and the **disagreement** power — the mean over members of the
    residual ``(member − mean)`` auto-power (the spectral decomposition of the
    per-pixel variance: *at which scales the members disagree / hallucinate*).

    :meth:`curves` then yields ``P_hr(k)``, ``P_sr(k)``, ``P_disagree(k)``, the
    cross-correlation coefficient ``r(k)`` (how correlated the ensemble mean is
    with the truth at scale k) and the transfer function ``T(k)``.
    """

    def __init__(self, n: int, pixel_scale_arcsec: float, *,
                 kmin: float = 0.2, nbins: int = 24) -> None:
        self.n = int(n)
        self.pix = float(pixel_scale_arcsec)
        self.k_edges = log_k_edges(self.pix, kmin, nbins)
        self.k_cen = np.sqrt(self.k_edges[:-1] * self.k_edges[1:])
        self.window = tukey_window_2d(self.n)
        self.nbins = int(nbins)
        z = lambda: np.zeros(nbins, dtype=np.float64)   # noqa: E731
        self.bh, self.bs, self.bx, self.bd, self.bc = z(), z(), z(), z(), z()
        self.member_bs: np.ndarray | None = None        # (M, nbins) per-member auto
        self.member_bx: np.ndarray | None = None        # (M, nbins) per-member ×HR
        self.n_fields = 0
        self.n_members = 0

    def add(self, hr: np.ndarray, mean: np.ndarray,
            members: np.ndarray) -> None:
        """Accumulate one field. ``hr``/``mean`` are ``(n, n)``; ``members`` is
        ``(M, n, n)`` — all single-band, HR-grid."""
        hr = np.asarray(hr, np.float64)
        mean = np.asarray(mean, np.float64)
        if hr.shape != (self.n, self.n) or mean.shape != hr.shape:
            return
        bh, bs, bx, bc = bin_powers(hr, mean, self.pix, self.k_edges, self.window)
        self.bh += bh; self.bs += bs; self.bx += bx; self.bc += bc
        members = np.asarray(members, np.float64)
        if members.ndim == 3 and members.shape[1:] == hr.shape and len(members):
            mm = int(len(members))
            if self.member_bs is None:
                self.member_bs = np.zeros((mm, self.nbins))
                self.member_bx = np.zeros((mm, self.nbins))
            per_member = mm == self.member_bs.shape[0]   # consistent M across fields
            dacc = np.zeros_like(bh)
            for i, m in enumerate(members):
                resid = m - mean
                ph, _ps, _px, _bc = bin_powers(
                    resid, resid, self.pix, self.k_edges, self.window)
                dacc += ph
                if per_member:                            # each member vs HR
                    _bh_i, bs_i, bx_i, _bc2 = bin_powers(
                        hr, m, self.pix, self.k_edges, self.window)
                    self.member_bs[i] += bs_i
                    self.member_bx[i] += bx_i
            self.bd += dacc / float(mm)
            self.n_members = max(self.n_members, mm)
        self.n_fields += 1

    def curves(self) -> dict[str, np.ndarray]:
        with np.errstate(divide="ignore", invalid="ignore"):
            p_hr = self.bh / self.bc
            p_sr = self.bs / self.bc
            p_dis = self.bd / self.bc
            r = self.bx / np.sqrt(self.bh * self.bs)
            t = np.sqrt(self.bs / self.bh)
            # HR-FREE inter-model coherence: average pairwise power correlation
            # between members. From the variance identity ⟨P_member⟩ = P_mean +
            # P_disagree and ρ = (M·coherent_frac − 1)/(M−1), with coherent_frac
            # = P_mean/⟨P_member⟩. ρ→1 = members agree (real), ρ→0 = decorrelated
            # (hallucination). Needs NO HR, so it applies to real images too.
            coherent_frac = self.bs / (self.bs + self.bd)
            m = max(self.n_members, 2)
            rho = (m * coherent_frac - 1.0) / (m - 1.0)
        empty = self.bc <= 0
        for arr in (p_hr, p_sr, p_dis, r, t, coherent_frac, rho):
            arr[empty] = np.nan
        out = {"k": self.k_cen, "P_hr": p_hr, "P_sr": p_sr,
               "P_disagree": p_dis, "r": r, "T": t,
               "coherent_frac": coherent_frac, "rho": rho}
        if self.member_bs is not None:
            with np.errstate(divide="ignore", invalid="ignore"):
                p_mem = self.member_bs / self.bc                       # (M, nb)
                r_mem = self.member_bx / np.sqrt(self.bh[None, :] * self.member_bs)
            p_mem[:, empty] = np.nan
            r_mem[:, empty] = np.nan
            out["P_members"] = p_mem
            out["r_members"] = r_mem
        return out


def coherence_half_scale(k: np.ndarray, c: np.ndarray) -> float | None:
    """The k (cyc/arcsec) where coherence ``c`` first drops below 0.5 — an
    HR-free "effective resolution". Log-interpolated; ``None`` if never crossed.
    """
    k = np.asarray(k, float)
    c = np.asarray(c, float)
    good = np.isfinite(k) & np.isfinite(c)
    k, c = k[good], c[good]
    for i in range(1, len(k)):
        if c[i - 1] >= 0.5 > c[i]:
            f = (0.5 - c[i - 1]) / (c[i] - c[i - 1])
            return float(np.exp(np.log(k[i - 1]) + f * (np.log(k[i]) - np.log(k[i - 1]))))
    return None


def ensemble_ps_plot_curves(curves: dict[str, np.ndarray]) -> dict[str, np.ndarray]:
    """Derive the VIS T(k)/r(k) plot arrays (per-member + ensemble mean).

    Pure transform of an :meth:`EnsembleSpectrumAccumulator.curves` dict. Returns
    ``{theta, T, T_members, r, r_members}`` where ``theta = 1/(2k)`` arcsec,
    ``T = sqrt(P_sr/P_hr)`` (mean), ``T_members[j] = sqrt(P_members[j]/P_hr)``,
    ``r`` is the ensemble mean vs HR, ``r_members`` the per-member correlations.
    Member arrays are ``(M, nbins)`` and empty ``(0, nbins)`` when <2 members.
    """
    k = np.asarray(curves.get("k", []), float)
    nan_k = np.full(k.size, np.nan)
    p_hr = np.asarray(curves.get("P_hr", nan_k), float)
    p_sr = np.asarray(curves.get("P_sr", nan_k), float)
    r = np.asarray(curves.get("r", nan_k), float)
    p_members = np.asarray(curves.get("P_members", np.empty((0, k.size))), float)
    r_members = np.asarray(curves.get("r_members", np.empty((0, k.size))), float)
    with np.errstate(divide="ignore", invalid="ignore"):
        theta = 0.5 / k
        t_mean = np.sqrt(p_sr / p_hr)
        t_members = (np.sqrt(p_members / p_hr[None, :])
                     if p_members.size else np.empty((0, k.size)))
    return {"theta": theta, "T": t_mean, "T_members": t_members,
            "r": r, "r_members": r_members}


def render_ensemble_power_spectrum(out_png: str, curves: dict[str, np.ndarray],
                                   *, n_fields: int = 0) -> str | None:
    """Two-panel ensemble power-spectrum figure (VIS band).

    Left: P(k) for HR, ensemble-mean SR, and the member disagreement (log-log).
    Right: r(k) — cross-correlation of ensemble mean with HR per scale (the
    "how correlated are the features" curve). A guide line marks the LR Nyquist
    (the super-resolution boundary). Returns the path, or ``None`` if empty.
    """
    k = np.asarray(curves.get("k", []), float)
    if k.size == 0 or not np.isfinite(np.asarray(curves.get("P_hr", []), float)).any():
        return None
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig, (ax_p, ax_r) = plt.subplots(1, 2, figsize=(13.0, 5.2))

    p_hr = np.asarray(curves["P_hr"], float)
    p_sr = np.asarray(curves["P_sr"], float)
    p_dis = np.asarray(curves["P_disagree"], float)
    r = np.asarray(curves["r"], float)

    # Individual members (faint, behind the summary lines).
    p_members = np.asarray(curves.get("P_members", np.empty((0, k.size))), float)
    for j, row in enumerate(p_members):
        ax_p.loglog(k, row, color=BAND_COLORS["VIS"], lw=0.6, alpha=0.28,
                    label=("individual members" if j == 0 else None))

    ax_p.loglog(k, p_hr, color="#222", lw=2.0, label="HR (truth)")
    ax_p.loglog(k, p_sr, color=BAND_COLORS["VIS"], lw=2.0, label="ensemble mean SR")
    ax_p.loglog(k, p_dis, color="#d6604d", lw=1.8, ls="--",
                label="member disagreement")
    ax_p.axvline(LR_NYQUIST_CYC_ARCSEC, color="grey", ls=":", lw=1.2)
    ax_p.text(LR_NYQUIST_CYC_ARCSEC * 1.04, ax_p.get_ylim()[0], "LR Nyquist",
              rotation=90, va="bottom", ha="left", fontsize=8, color="grey")
    ax_p.set_xlabel("k  [cycles / arcsec]")
    ax_p.set_ylabel("power  P(k)  [arb.]")
    ax_p.set_title("Angular power spectrum — VIS"
                   + (f"  ({n_fields} fields)" if n_fields else ""))
    ax_p.legend(fontsize=9, frameon=False)
    ax_p.grid(True, which="both", alpha=0.15)

    rho = np.asarray(curves.get("rho", np.full_like(k, np.nan)), float)
    has_hr = np.isfinite(r).any()
    # Individual members vs HR (faint, behind the summary lines).
    r_members = np.asarray(curves.get("r_members", np.empty((0, k.size))), float)
    for j, row in enumerate(r_members):
        ax_r.plot(k, row, color="#3b6fb0", lw=0.6, alpha=0.22,
                  label=("individual members vs HR" if j == 0 else None))
    # ρ(k): inter-model coherence — needs NO HR, so it also works on real data.
    ax_r.plot(k, rho, color="#5aae61", lw=2.3, label="ρ(k): inter-model (HR-free)")
    if has_hr:
        ax_r.plot(k, r, color="#3b6fb0", lw=2.0, ls="--",
                  label="r(k): vs HR (truth)")
    k_half = coherence_half_scale(k, rho)
    if k_half:
        ax_r.axvline(k_half, color="#3a7d3a", ls="-.", lw=1.0, alpha=0.8)
        ax_r.text(k_half * 1.04, 0.04, f"ρ=½ @ {k_half:.1f}", rotation=90,
                  va="bottom", ha="left", fontsize=8, color="#3a7d3a")
    ax_r.axvline(LR_NYQUIST_CYC_ARCSEC, color="grey", ls=":", lw=1.2)
    ax_r.axhline(0.5, color="grey", lw=0.6, alpha=0.4)
    ax_r.axhline(1.0, color="grey", lw=0.8, alpha=0.5)
    ax_r.set_xscale("log")
    ax_r.set_ylim(0.0, 1.02)
    ax_r.set_xlabel("k  [cycles / arcsec]")
    ax_r.set_ylabel("coherence")
    ax_r.set_title("Coherence: agree (→1) vs invent (→0) — HR-free ρ vs truth r")
    ax_r.legend(fontsize=8, frameon=False, loc="lower left")
    ax_r.grid(True, which="both", alpha=0.15)

    fig.tight_layout()
    fig.savefig(out_png, dpi=150, bbox_inches="tight")
    plt.close(fig)
    return out_png


# test-only; production uses BandStat
class _SpectrumAccumulator:
    """Raw-sum stacked auto/cross power on a fixed physical k-grid.

    Sums power across objects, the standard stacked-spectrum estimator. NOTE:
    because power scales as flux², a few extreme-flux objects dominate this sum,
    so the renderer prefers a per-object *median* (see ``BandStat``); this class
    backs the low-level math/unit tests and physical k-grid combination of
    different stamp sizes.
    """

    def __init__(self, k_edges: np.ndarray):
        self.k_edges = np.asarray(k_edges, dtype=np.float64)
        nb = len(self.k_edges) - 1
        self.sum_hr = np.zeros(nb)
        self.sum_sr = np.zeros(nb)
        self.sum_cross = np.zeros(nb)
        self.count = np.zeros(nb)
        self.n_obj = 0

    def add(
        self,
        hr: np.ndarray,
        sr: np.ndarray,
        pixel_scale_arcsec: float,
        window: np.ndarray | None = None,
    ) -> None:
        """Add one HR/SR plane pair (same shape) to the ensemble."""
        bh, bs, bx, bc = bin_powers(hr, sr, pixel_scale_arcsec, self.k_edges, window)
        self.sum_hr += bh
        self.sum_sr += bs
        self.sum_cross += bx
        self.count += bc
        self.n_obj += 1

    def finalize(self) -> dict[str, np.ndarray]:
        """Return ``{k, T, r, p_hr, p_sr, count}``; empty bins are NaN."""
        kc = np.sqrt(self.k_edges[:-1] * self.k_edges[1:])
        t, r = ratios_from_powers(
            self.sum_hr, self.sum_sr, self.sum_cross, self.count
        )
        return {
            "k": kc, "T": t, "r": r,
            "p_hr": self.sum_hr.copy(), "p_sr": self.sum_sr.copy(),
            "count": self.count.copy(),
        }


class BandStat:
    """Per-object T(k)/r(k) curves for one band, aggregated by median.

    Equal-weight across objects (robust to flux outliers): each object yields one
    bounded ``r_i(k) ∈ [-1, 1]`` and ``T_i(k)``; we report the median curve plus
    the 16–84% inter-object spread.
    """

    def __init__(self, k_edges: np.ndarray):
        self.k_edges = np.asarray(k_edges, dtype=np.float64)
        self.kc = np.sqrt(self.k_edges[:-1] * self.k_edges[1:])
        self._t_rows: list[np.ndarray] = []
        self._r_rows: list[np.ndarray] = []

    @property
    def n_obj(self) -> int:
        return len(self._t_rows)

    def add(
        self,
        hr: np.ndarray,
        sr: np.ndarray,
        pixel_scale_arcsec: float,
        window: np.ndarray | None = None,
    ) -> None:
        bh, bs, bx, bc = bin_powers(hr, sr, pixel_scale_arcsec, self.k_edges, window)
        t, r = ratios_from_powers(bh, bs, bx, bc)
        self._t_rows.append(t)
        self._r_rows.append(r)

    def finalize(self) -> dict[str, np.ndarray]:
        nb = len(self.kc)
        if not self._t_rows:
            nan = np.full(nb, np.nan)
            return {"k": self.kc, "T": nan, "r": nan, "T_lo": nan, "T_hi": nan,
                    "r_lo": nan, "r_hi": nan, "count": np.zeros(nb), "n_obj": 0}
        import warnings

        T = np.vstack(self._t_rows)
        R = np.vstack(self._r_rows)
        count = np.sum(np.isfinite(R), axis=0).astype(float)
        with np.errstate(all="ignore"), warnings.catch_warnings():
            warnings.simplefilter("ignore", RuntimeWarning)  # all-NaN low-k bins
            out = {
                "k": self.kc,
                "T": np.nanmedian(T, axis=0),
                "T_lo": np.nanpercentile(T, 16, axis=0),
                "T_hi": np.nanpercentile(T, 84, axis=0),
                "r": np.nanmedian(R, axis=0),
                "r_lo": np.nanpercentile(R, 16, axis=0),
                "r_hi": np.nanpercentile(R, 84, axis=0),
                "count": count,
                "n_obj": self.n_obj,
            }
        empty = count <= 0
        for key in ("T", "T_lo", "T_hi", "r", "r_lo", "r_hi"):
            out[key][empty] = np.nan
        return out


