def render_power_spectrum_summary(
    out_png: str, subset: str | None = None
) -> str | None:
    """Render the per-band HR-vs-SR power-spectrum figure → ``out_png``.

    Two rows (linear electrons / asinh space) × two columns (transfer function
    ``T(k)`` and cross-correlation ``r(k)``), one curve per band, aggregated as a
    per-field median over the sky validation fields (HR ``clean`` record vs
    generated SR cube, paired by record index). Returns the PNG path, or ``None``
    when the records aren't synced or no SR has been generated yet.
    """
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    from euclid_polish.eval.subsets import eval_subset
    from euclid_polish.image.tfio import read_images, tfrecord_path
    from euclid_polish.web.helpers import sky_records
    from euclid_polish.web.helpers.paths import _sky_records_local_dir

    records_dir = _sky_records_local_dir()
    # Default to the held-out test split (else validate) when not specified.
    if subset is None:
        subset = eval_subset(records_dir)
    clean_path = tfrecord_path(records_dir, f"clean_{subset}")
    n_sr = sky_records.sr_count(subset)
    if not os.path.exists(clean_path) or n_sr == 0:
        return None
    records = read_images(clean_path, num_images=n_sr)
    if not records:
        return None

    band_names = list(Config.LR_INPUT_BAND_NAMES)  # (VIS, Y_E, J_E, H_E)
    pixel_scale = float(Config.DEFAULT_PIXEL_SCALE)  # 0.05" HR/SR grid
    # large fields → push the low-k edge well below the 106²-stamp limit
    k_edges = log_k_edges(pixel_scale, kmin=0.06, nbins=28)
    spaces = ("linear", "asinh")

    # one per-field-median stat per (space, band)
    accs: dict[tuple[str, str], BandStat] = {
        (sp, b): BandStat(k_edges) for sp in spaces for b in band_names
    }
    stretch = float(Config.STRETCH_SCALE_E)

    field_n = 0
    n_used = 0
    for i, rec in enumerate(records):
        sr_file = sky_records.sr_path(subset, i)
        if not os.path.isfile(sr_file):
            continue
        try:
            hr_cube = _bands_from_cube(rec.data)
            sr_cube = _bands_from_cube(np.load(sr_file))
        except Exception:
            continue
        used = False
        for bi, bname in enumerate(band_names):
            if bi not in hr_cube or bi not in sr_cube:
                continue
            hr = hr_cube[bi]
            sr = sr_cube[bi]
            if hr.shape != sr.shape:
                continue
            field_n = hr.shape[0]
            win = tukey_window_2d(hr.shape[0])
            accs[("linear", bname)].add(hr, sr, pixel_scale, win)
            accs[("asinh", bname)].add(
                np.arcsinh(hr / stretch), np.arcsinh(sr / stretch), pixel_scale, win
            )
            used = True
        n_used += int(used)

    if n_used == 0:
        return None

    # finalize once per (space, band)
    res = {(sp, b): accs[(sp, b)].finalize() for sp in spaces for b in band_names}

    from matplotlib.ticker import FuncFormatter, NullFormatter

    # plot against angular scale θ = 1/(2k) [arcsec] — the size of the finest
    # resolvable feature: at the HR Nyquist that is one 0.05″ pixel.
    def to_scale(k):
        return 0.5 / np.asarray(k, dtype=float)

    scale_lo = float(Config.DEFAULT_PIXEL_SCALE)             # 0.05″ = HR pixel
    scale_hi = 0.5 / k_edges[0]                              # coarsest probed scale
    lr_scale = 0.5 / LR_NYQUIST_CYC_ARCSEC                   # 0.10″ LR sampling
    xticks = [0.05, 0.1, 0.2, 0.5, 1.0, 2.0, 5.0]

    fig, axes = plt.subplots(2, 2, figsize=(13.0, 9.5))
    col_meta = (
        (0, "T", "transfer function  T = √(P_SR/P_HR)", (0.0, 1.45)),
        (1, "r", "cross-correlation  r = P_HR×SR/√(P_HR·P_SR)", (0.0, 1.05)),
    )
    for ri, sp in enumerate(spaces):
        for ci, key, short, ylim in col_meta:
            ax = axes[ri, ci]
            for bname in band_names:
                rb = res[(sp, bname)]
                x = to_scale(rb["k"])
                color = BAND_COLORS.get(bname, "#444")
                ax.fill_between(x, rb[key + "_lo"], rb[key + "_hi"],
                                color=color, alpha=0.12, lw=0)
                ax.plot(x, rb[key], "-o", ms=3.0, lw=1.7, color=color, label=bname)
            ax.axhline(1.0, ls=":", color="#888", lw=1.0)
            # LR sampling scale (0.10″) — above this is super-resolution
            ax.axvline(lr_scale, ls="--", color="#333", lw=1.3,
                       label="LR sampling (0.1″)" if (ri == 0 and ci == 0) else None)
            # per-band PSF FWHM (the band's true resolution scale), clearly visible
            for bname in band_names:
                fwhm = float(Config.get_band(bname).psf_fwhm_arcsec)
                ax.axvline(fwhm, ls=(0, (5, 2)), lw=1.5, alpha=0.55,
                           color=BAND_COLORS.get(bname, "#444"))
            ax.set_xscale("log")
            ax.set_xlim(scale_lo, scale_hi)
            ax.set_ylim(*ylim)
            ax.set_xticks(xticks)
            ax.xaxis.set_major_formatter(FuncFormatter(lambda v, _: f"{v:g}"))
            ax.xaxis.set_minor_formatter(NullFormatter())
            ax.set_xlabel("angular scale  θ = 1/2k  [arcsec]   (0.05″ = HR pixel)")
            ax.set_ylabel(f"{key}  [{sp}]")
            ax.grid(alpha=0.2)
            ax.set_title(f"{sp} — {short}")
    axes[1, 1].legend(fontsize=8, loc="lower right", ncol=2)

    fig.suptitle(
        "Angular power spectrum — HR vs SR (sky validation fields, "
        f"per-field median ± 16–84%)\n{n_used} fields · "
        f"{field_n}×{field_n} @ 0.05″ · finer (smaller θ) → left · "
        "dashed coloured = per-band PSF FWHM · dashed black = LR sampling (0.1″)",
        fontsize=12,
    )
    fig.tight_layout(rect=(0, 0, 1, 0.95))
    os.makedirs(os.path.dirname(out_png) or ".", exist_ok=True)
    fig.savefig(out_png, dpi=150, bbox_inches="tight")
    plt.close(fig)
    return out_png
