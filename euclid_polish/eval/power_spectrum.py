"""Angular (flat-sky 2D Fourier) power-spectrum comparison of HR vs SR.

For each band we measure, in the Fourier domain and averaged azimuthally:

- the **transfer function** ``T(k) = sqrt(P_SR(k) / P_HR(k))`` — whether SR
  carries the right amount of power at scale ``k`` (over-smoothing → T<1,
  hallucinated/excess power → T>1), and
- the **cross-correlation coefficient** ``r(k) = P_HR×SR(k) /
  sqrt(P_HR(k)·P_SR(k))`` — whether the power at ``k`` is the *real* structure
  (r→1) or decorrelated/invented (r→0).

``r(k)`` is the direct answer to "how well does the model resolve features",
especially in the super-resolution regime above the LR sampling limit
(5 cyc/arcsec on the 0.10" LR grid) up to the HR-grid Nyquist (10 cyc/arcsec on
the 0.05" SR/HR grid).

We run this on the **sky validation set** synced through the /sky tab — large
fields (≈510×510 at 0.05"), which carry far more Fourier modes per k-bin (so
T(k)/r(k) are smooth) and real structure across scales, unlike the mode-starved
106² evaluation cutouts. HR is the ``clean`` record (the deconvolved-sky target
the model is trained to output); SR is the per-field cube generated by the /sky
"Generate SR" button (``data/vis/sky_sr/sr_<subset>_<idx>.npy``), paired by
record index.

Estimator: per-**field** median ± 16–84% inter-field spread (each field weighted
equally). This is deliberate — a single bright star carries ~flux², so a few
star-dominated fields (which the model rejects by design) would otherwise
dominate a raw stacked sum; the median is robust to them, and the asinh space
further compresses their dynamic range.

The math (window, binning, ratios) is pure numpy/scipy; the renderer lazily
imports matplotlib and the TFRecord/sky loaders.
"""

from __future__ import annotations

import os
import warnings

import numpy as np

from euclid_polish.config import Config

#: per-band line colours (blue→red, roughly by pivot wavelength)
BAND_COLORS: dict[str, str] = {
    "VIS": "#3b6fb0", "Y_E": "#5aae61", "J_E": "#e08214", "H_E": "#d6604d",
}

#: LR sampling Nyquist on the 0.10" grid — the super-resolution boundary.
LR_NYQUIST_CYC_ARCSEC = 1.0 / (2.0 * Config.VIS_PIXEL_SCALE_ARCSEC)  # 5.0


# --------------------------------------------------------------------------- #
# Core math (unit-tested)                                                      #
# --------------------------------------------------------------------------- #
def tukey_window_2d(n: int, alpha: float = 0.25) -> np.ndarray:
    """Separable 2D Tukey window (``n×n``) to suppress finite-stamp leakage."""
    from scipy.signal.windows import tukey

    w = tukey(n, alpha)
    return np.outer(w, w)


def cross_power_2d(
    a: np.ndarray, b: np.ndarray, window: np.ndarray | None = None
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """2D auto/cross power for two same-shape real images.

    Each image is mean-subtracted (kills the DC term) and multiplied by
    ``window`` before the FFT. Returns ``(P_aa, P_bb, P_ab)`` as unshifted 2D
    real arrays, where ``P_ab = Re(A · conj(B))``.
    """
    a = np.asarray(a, dtype=np.float64)
    b = np.asarray(b, dtype=np.float64)
    if a.shape != b.shape:
        raise ValueError(f"shape mismatch: {a.shape} vs {b.shape}")
    if window is not None:
        a = (a - a.mean()) * window
        b = (b - b.mean()) * window
    else:
        a = a - a.mean()
        b = b - b.mean()
    fa = np.fft.fft2(a)
    fb = np.fft.fft2(b)
    p_aa = (fa * np.conj(fa)).real
    p_bb = (fb * np.conj(fb)).real
    p_ab = (fa * np.conj(fb)).real
    return p_aa, p_bb, p_ab


def k_magnitude_2d(n: int, pixel_scale_arcsec: float) -> np.ndarray:
    """``|k|`` (cycles/arcsec) for an ``n×n`` unshifted FFT grid."""
    f = np.fft.fftfreq(n, d=pixel_scale_arcsec)  # cycles / arcsec
    kx, ky = np.meshgrid(f, f, indexing="xy")
    return np.hypot(kx, ky)


def log_k_edges(
    pixel_scale_arcsec: float, kmin: float = 0.2, nbins: int = 24
) -> np.ndarray:
    """Log-spaced k-bin edges from ``kmin`` to the Nyquist ``1/(2·pixscale)``."""
    k_nyq = 1.0 / (2.0 * pixel_scale_arcsec)
    return np.geomspace(kmin, k_nyq, nbins + 1)


def bin_powers(
    hr: np.ndarray,
    sr: np.ndarray,
    pixel_scale_arcsec: float,
    k_edges: np.ndarray,
    window: np.ndarray | None = None,
) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """Azimuthally-binned ``(p_hr, p_sr, p_cross, count)`` for one HR/SR pair."""
    n = hr.shape[0]
    if window is None:
        window = tukey_window_2d(n)
    p_hr2, p_sr2, p_x2 = cross_power_2d(hr, sr, window)
    kmag = k_magnitude_2d(n, pixel_scale_arcsec).ravel()
    nb = len(k_edges) - 1
    idx = np.digitize(kmag, np.asarray(k_edges, float)) - 1
    keep = (idx >= 0) & (idx < nb)
    idx = idx[keep]
    bh = np.bincount(idx, weights=p_hr2.ravel()[keep], minlength=nb)
    bs = np.bincount(idx, weights=p_sr2.ravel()[keep], minlength=nb)
    bx = np.bincount(idx, weights=p_x2.ravel()[keep], minlength=nb)
    bc = np.bincount(idx, minlength=nb).astype(float)
    return bh, bs, bx, bc


def pairwise_cross_correlation(
    images: list[np.ndarray],
    pixel_scale_arcsec: float,
    k_edges: np.ndarray,
    window: np.ndarray | None = None,
) -> np.ndarray:
    """Azimuthally-binned cross-correlation ``r_ij(k)`` for every image pair.

    One FFT per image (not per pair): each image is mean-subtracted, windowed
    and transformed once, then the binned auto/cross powers come from the
    cached spectra. Returns ``(n_pairs, nbins)`` rows ordered ``(0,1), (0,2),
    …`` (``i < j``); empty k-bins are NaN. Fewer than two images → ``(0,
    nbins)``.
    """
    k_edges = np.asarray(k_edges, float)
    nb = len(k_edges) - 1
    m = len(images)
    if m < 2:
        return np.empty((0, nb))
    n = images[0].shape[0]
    if window is None:
        window = tukey_window_2d(n)
    kmag = k_magnitude_2d(n, pixel_scale_arcsec).ravel()
    idx = np.digitize(kmag, k_edges) - 1
    keep = (idx >= 0) & (idx < nb)
    idx = idx[keep]
    ffts = []
    for im in images:
        a = np.asarray(im, np.float64)
        ffts.append(np.fft.fft2((a - a.mean()) * window))
    autos = [np.bincount(idx, weights=(f * np.conj(f)).real.ravel()[keep],
                         minlength=nb) for f in ffts]
    bc = np.bincount(idx, minlength=nb).astype(float)
    rows = []
    for i in range(m):
        for j in range(i + 1, m):
            bx = np.bincount(
                idx, weights=(ffts[i] * np.conj(ffts[j])).real.ravel()[keep],
                minlength=nb)
            with np.errstate(divide="ignore", invalid="ignore"):
                r = bx / np.sqrt(autos[i] * autos[j])
            r[bc <= 0] = np.nan
            rows.append(r)
    return np.vstack(rows)


def ratios_from_powers(
    bh: np.ndarray, bs: np.ndarray, bx: np.ndarray, bc: np.ndarray
) -> tuple[np.ndarray, np.ndarray]:
    """``(T, r)`` from binned powers; empty bins → NaN. r ∈ [-1, 1] per object."""
    with np.errstate(divide="ignore", invalid="ignore"):
        t = np.sqrt(bs / bh)
        r = bx / np.sqrt(bh * bs)
    empty = bc <= 0
    t[empty] = np.nan
    r[empty] = np.nan
    return t, r


# --------------------------------------------------------------------------- #
# Ensemble power spectrum: HR vs ensemble-mean + the disagreement spectrum     #
# --------------------------------------------------------------------------- #
class EnsembleSpectrumAccumulator:
    """Stacked HR / ensemble-mean / disagreement power on a fixed k-grid.

    Fed one field at a time (single band, HR-grid resolution). Accumulates, per
    azimuthal k-bin: HR auto-power, ensemble-mean SR auto-power, the HR×mean
    cross-power, and the **disagreement** power — the mean over members of the
    residual ``(member − mean)`` auto-power (the spectral decomposition of the
    per-pixel variance: *at which scales the members disagree / hallucinate*).

    :meth:`curves` then yields ``P_hr(k)``, ``P_sr(k)``, ``P_disagree(k)``, the
    cross-correlation coefficient ``r(k)`` (how correlated the ensemble mean is
    with the truth at scale k) and the transfer function ``T(k)``.
    """

    def __init__(self, n: int, pixel_scale_arcsec: float, *,
                 kmin: float = 0.06, nbins: int = 28,
                 stretch: float | None = None) -> None:
        self.n = int(n)
        self.pix = float(pixel_scale_arcsec)
        # asinh compression scale — matches the /evaluation power spectrum, so a
        # few saturated/bright sources (≈ white spectrum in raw electrons) don't
        # dominate and decorrelate the cross-power at every scale.
        self.stretch = float(stretch if stretch is not None else Config.STRETCH_SCALE_E)
        self.k_edges = log_k_edges(self.pix, kmin, nbins)
        self.k_cen = np.sqrt(self.k_edges[:-1] * self.k_edges[1:])
        self.window = tukey_window_2d(self.n)
        self.nbins = int(nbins)
        self.bc = np.zeros(nbins, dtype=np.float64)     # summed mode counts
        # Per-FIELD rows → median-aggregated in curves() (robust to flux outliers,
        # like the evaluation's BandStat). Each holds one bounded curve per field.
        self._p_hr: list[np.ndarray] = []
        self._p_sr: list[np.ndarray] = []
        self._p_dis: list[np.ndarray] = []
        self._r: list[np.ndarray] = []
        self._t: list[np.ndarray] = []
        self._rho: list[np.ndarray] = []
        self._r_members: list[np.ndarray] = []          # each (M, nbins)
        self._p_members: list[np.ndarray] = []          # each (M, nbins)
        self._r_pairs: list[np.ndarray] = []            # each (M·(M−1)/2, nbins)
        self._p_comb: list[np.ndarray] = []             # combiner auto-power
        self._r_comb: list[np.ndarray] = []             # combiner vs HR coherence
        self.n_fields = 0
        self.n_members = 0
        self.has_combiner = False

    def _asinh(self, x: np.ndarray) -> np.ndarray:
        return np.arcsinh(np.asarray(x, np.float64) / self.stretch)

    def add(self, hr: np.ndarray, mean: np.ndarray,
            members: np.ndarray, combiner: np.ndarray | None = None) -> None:
        """Accumulate one field (asinh space). ``hr``/``mean`` are ``(n, n)``;
        ``members`` is ``(M, n, n)`` — all single-band, HR-grid. ``combiner``
        (optional, ``(n, n)``) is the combined reconstruction → its own
        ``P_comb``/``r_comb`` series alongside the ensemble mean."""
        hr = np.asarray(hr, np.float64)
        mean = np.asarray(mean, np.float64)
        if hr.shape != (self.n, self.n) or mean.shape != hr.shape:
            return
        ah = self._asinh(hr)
        members = np.asarray(members, np.float64)
        have = members.ndim == 3 and members.shape[1:] == hr.shape and len(members)
        # asinh-space ensemble "mean" = mean of the asinh members (keeps the
        # variance identity ⟨P_member⟩ = P_mean + P_disagree exact); falls back to
        # asinh(raw mean) with no members.
        am = [self._asinh(m) for m in members] if have else None
        asm = np.mean(np.stack(am, 0), 0) if have else self._asinh(mean)

        bh, bs, bx, bc = bin_powers(ah, asm, self.pix, self.k_edges, self.window)
        self.bc += bc
        with np.errstate(divide="ignore", invalid="ignore"):
            p_hr, p_sr = bh / bc, bs / bc
        t, r = ratios_from_powers(bh, bs, bx, bc)

        p_dis = np.full(self.nbins, np.nan)
        rho = np.full(self.nbins, np.nan)
        if have:
            mm = len(am)
            dacc = np.zeros(self.nbins)
            r_rows, p_rows = [], []
            for amk in am:
                resid = amk - asm
                ph, _ps, _px, _bc = bin_powers(resid, resid, self.pix, self.k_edges, self.window)
                dacc += ph
                _bh, bsk, bxk, bck = bin_powers(ah, amk, self.pix, self.k_edges, self.window)
                _tk, rk = ratios_from_powers(_bh, bsk, bxk, bck)
                r_rows.append(rk)
                with np.errstate(divide="ignore", invalid="ignore"):
                    p_rows.append(bsk / bck)
            with np.errstate(divide="ignore", invalid="ignore"):
                p_dis = (dacc / float(mm)) / bc
                coh = p_sr / (p_sr + p_dis)
                mfac = max(mm, 2)
                rho = (mfac * coh - 1.0) / (mfac - 1.0)
            if not self.n_members or mm == self.n_members:
                self._r_members.append(np.vstack(r_rows))
                self._p_members.append(np.vstack(p_rows))
                # model–model cross-correlation per pair: the truth-free
                # counterpart of r(k) — where members agree spectrally.
                self._r_pairs.append(pairwise_cross_correlation(
                    am, self.pix, self.k_edges, self.window))
                self.n_members = mm

        empty = bc <= 0
        for a in (p_hr, p_sr, p_dis, r, t, rho):
            a[empty] = np.nan
        self._p_hr.append(p_hr); self._p_sr.append(p_sr); self._p_dis.append(p_dis)
        self._r.append(r); self._t.append(t); self._rho.append(rho)

        # Combiner: its own auto-power + HR cross-correlation (asinh space).
        if combiner is not None:
            ac = self._asinh(np.asarray(combiner, np.float64))
            if ac.shape == hr.shape:
                _bhc, bsc, bxc, bcc = bin_powers(ah, ac, self.pix,
                                                 self.k_edges, self.window)
                _tc, rc = ratios_from_powers(_bhc, bsc, bxc, bcc)
                with np.errstate(divide="ignore", invalid="ignore"):
                    pc = bsc / bcc
                ce = bcc <= 0
                pc[ce] = np.nan; rc[ce] = np.nan
                self._p_comb.append(pc); self._r_comb.append(rc)
                self.has_combiner = True
        self.n_fields += 1

    def _med(self, rows: list[np.ndarray]) -> np.ndarray:
        if not rows:
            return np.full(self.nbins, np.nan)
        with np.errstate(all="ignore"), warnings.catch_warnings():
            warnings.simplefilter("ignore", RuntimeWarning)   # all-NaN low-k bins
            return np.nanmedian(np.vstack(rows), axis=0)

    def curves(self) -> dict[str, np.ndarray]:
        out = {"k": self.k_cen,
               "P_hr": self._med(self._p_hr), "P_sr": self._med(self._p_sr),
               "P_disagree": self._med(self._p_dis),
               "r": self._med(self._r), "T": self._med(self._t),
               "rho": self._med(self._rho)}
        if self._r_members:
            with np.errstate(all="ignore"), warnings.catch_warnings():
                warnings.simplefilter("ignore", RuntimeWarning)
                out["r_members"] = np.nanmedian(np.stack(self._r_members, 0), axis=0)
                out["P_members"] = np.nanmedian(np.stack(self._p_members, 0), axis=0)
        if self._r_pairs:
            with np.errstate(all="ignore"), warnings.catch_warnings():
                warnings.simplefilter("ignore", RuntimeWarning)
                # per-pair median over fields, then a single median curve
                out["r_pairs"] = np.nanmedian(np.stack(self._r_pairs, 0), axis=0)
                out["r_cross"] = np.nanmedian(out["r_pairs"], axis=0)
        if self._p_comb:
            out["P_comb"] = self._med(self._p_comb)
            out["r_comb"] = self._med(self._r_comb)
        return out


def ensemble_ps_plot_curves(curves: dict[str, np.ndarray]) -> dict[str, np.ndarray]:
    """Derive the VIS T(k)/r(k) plot arrays (per-member + ensemble mean).

    Pure transform of an :meth:`EnsembleSpectrumAccumulator.curves` dict. Returns
    ``{theta, T, T_members, r, r_members}`` where ``theta = 1/(2k)`` arcsec,
    ``T = sqrt(P_sr/P_hr)`` (mean), ``T_members[j] = sqrt(P_members[j]/P_hr)``,
    ``r`` is the ensemble mean vs HR, ``r_members`` the per-member correlations,
    ``r_pairs``/``r_cross`` the model–model cross-correlations (per pair /
    median). Member arrays are ``(M, nbins)`` and empty ``(0, nbins)`` when <2
    members.
    """
    k = np.asarray(curves.get("k", []), float)
    nan_k = np.full(k.size, np.nan)
    p_hr = np.asarray(curves.get("P_hr", nan_k), float)
    p_sr = np.asarray(curves.get("P_sr", nan_k), float)
    r = np.asarray(curves.get("r", nan_k), float)
    p_members = np.asarray(curves.get("P_members", np.empty((0, k.size))), float)
    r_members = np.asarray(curves.get("r_members", np.empty((0, k.size))), float)
    r_pairs = np.asarray(curves.get("r_pairs", np.empty((0, k.size))), float)
    r_cross = np.asarray(curves.get("r_cross", nan_k), float)
    p_comb = np.asarray(curves.get("P_comb", nan_k), float)
    r_comb = np.asarray(curves.get("r_comb", nan_k), float)
    with np.errstate(divide="ignore", invalid="ignore"):
        theta = 0.5 / k
        t_mean = np.sqrt(p_sr / p_hr)
        t_members = (np.sqrt(p_members / p_hr[None, :])
                     if p_members.size else np.empty((0, k.size)))
        t_comb = np.sqrt(p_comb / p_hr)
    return {"theta": theta, "T": t_mean, "T_members": t_members,
            "r": r, "r_members": r_members,
            "r_pairs": r_pairs, "r_cross": r_cross,
            "T_comb": t_comb, "r_comb": r_comb}


#: Categorical colors for the per-member line grouping in the ensemble
#: power-spectrum figure. Loss norms get fixed colors; depths cycle.
LOSS_LINE_COLORS = {"l1": "#3b6fb0", "l2": "#5aae61", "l3": "#e08214",
                    "berhu": "#9970ab"}
GROUP_PALETTE = ["#3b6fb0", "#5aae61", "#e08214", "#d6604d",
                 "#9970ab", "#e8c944", "#59c7d6", "#e07356"]


def _member_group_colors(member_meta, color_by):
    """Per-member ``(group_label, color)`` for ``color_by`` ∈ {"loss",
    "depth"}; ``None`` when grouping is off/unavailable."""
    if not member_meta or color_by not in ("loss", "depth"):
        return None
    out = []
    if color_by == "loss":
        for m in member_meta:
            loss = str(m.get("loss") or "l1").lower()
            out.append((loss.upper(),
                        LOSS_LINE_COLORS.get(loss, GROUP_PALETTE[0])))
        return out
    depths = sorted({int(m["blocks"]) for m in member_meta if m.get("blocks")})
    by_depth = {d: GROUP_PALETTE[i % len(GROUP_PALETTE)]
                for i, d in enumerate(depths)}
    for m in member_meta:
        b = m.get("blocks")
        out.append((f"{int(b)}b", by_depth[int(b)]) if b
                   else ("?", "#7a8292"))
    return out


def render_ensemble_power_spectrum(out_png: str, curves: dict[str, np.ndarray],
                                   *, n_fields: int = 0,
                                   member_meta: list[dict] | None = None,
                                   color_by: str | None = None) -> str | None:
    """VIS ensemble power spectrum in the evaluation-page idiom (test fields).

    Two panels — left the transfer function ``T(k) = sqrt(P_SR/P_HR)``, right the
    cross-correlation ``r(k)`` — each drawn against angular scale ``theta =
    1/(2k)`` (arcsec) on a log axis. Every ensemble member is a faint line; the
    ensemble mean is bold. Guides: LR sampling (0.10\") and the VIS PSF FWHM.

    ``member_meta`` (one ``{"loss", "blocks"}`` dict per member, positional)
    + ``color_by`` ∈ {"loss", "depth"} colors the member lines by that
    grouping, one legend entry per group — a mixed L1/L2/L3 (or mixed-depth)
    ensemble at a glance. Default: all members in the faint VIS blue.

    Returns the path, or ``None`` when there is no finite HR power.
    """
    k = np.asarray(curves.get("k", []), float)
    if k.size == 0 or not np.isfinite(np.asarray(curves.get("P_hr", []), float)).any():
        return None
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.ticker import FuncFormatter, NullFormatter

    cv = ensemble_ps_plot_curves(curves)
    x = cv["theta"]
    vis_color = BAND_COLORS["VIS"]
    vis_fwhm = float(Config.get_band("VIS").psf_fwhm_arcsec)
    lr_scale = 0.5 / LR_NYQUIST_CYC_ARCSEC                 # 0.10" LR sampling
    scale_lo = float(Config.DEFAULT_PIXEL_SCALE)           # 0.05" HR pixel
    scale_hi = float(np.nanmax(x)) if np.isfinite(x).any() else 1.0
    xticks = [0.05, 0.1, 0.2, 0.5, 1.0, 2.0, 5.0]

    fig, (ax_t, ax_r) = plt.subplots(1, 2, figsize=(13.0, 5.2))
    panels = (
        (ax_t, cv["T"], cv["T_members"],
         "transfer function  T = √(P_SR/P_HR)", (0.0, 1.45), "T(k)  [VIS]"),
        (ax_r, cv["r"], cv["r_members"],
         "cross-correlation  r = P_HR×SR/√(P_HR·P_SR)", (0.0, 1.05), "r(k)  [VIS]"),
    )
    groups = _member_group_colors(member_meta, color_by)
    for ax, mean_curve, member_curves, title, ylim, ylabel in panels:
        seen_groups: set[str] = set()
        for j, row in enumerate(member_curves):
            if groups is not None and j < len(groups):
                glabel, gcolor = groups[j]
                ax.plot(x, row, color=gcolor, lw=0.9, alpha=0.55,
                        label=(glabel if glabel not in seen_groups else None))
                seen_groups.add(glabel)
            else:
                ax.plot(x, row, color=vis_color, lw=0.7, alpha=0.30,
                        label=("individual models" if j == 0 else None))
        ax.plot(x, mean_curve, "-o", ms=3.0, lw=2.0, color=vis_color,
                label="ensemble mean")
        if ax is ax_r and cv["r_pairs"].size:
            # model–model cross-correlation: the truth-free proxy for r(k).
            # Where it tracks the HR curve, inter-model agreement predicts
            # agreement with the truth — usable on real Euclid images.
            for j, row in enumerate(cv["r_pairs"]):
                ax.plot(x, row, color="#777", lw=0.6, alpha=0.18,
                        label=("model pairs" if j == 0 else None))
            ax.plot(x, cv["r_cross"], ls="--", lw=2.0, color="#555",
                    label="model–model median r̃(k) (no HR needed)")
        ax.axhline(1.0, ls=":", color="#888", lw=1.0)
        ax.axvline(lr_scale, ls="--", color="#333", lw=1.3,
                   label="LR sampling (0.1″)")
        ax.axvline(vis_fwhm, ls=(0, (5, 2)), lw=1.5, alpha=0.55, color=vis_color,
                   label="VIS PSF FWHM")
        ax.set_xscale("log")
        ax.set_xlim(scale_lo, scale_hi)
        ax.set_ylim(*ylim)
        ax.set_xticks(xticks)
        ax.xaxis.set_major_formatter(FuncFormatter(lambda v, _: f"{v:g}"))
        ax.xaxis.set_minor_formatter(NullFormatter())
